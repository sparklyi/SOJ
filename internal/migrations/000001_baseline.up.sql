    checker_message text,
    output_diff_summary text,
    created_at timestamptz DEFAULT now() NOT NULL,
    CONSTRAINT judge_case_results_case_index_check CHECK (case_index > 0),
    CONSTRAINT judge_case_results_memory_kb_check CHECK ((memory_kb IS NULL) OR (memory_kb >= 0)),
    CONSTRAINT judge_case_results_score_check CHECK (score >= 0),
    CONSTRAINT judge_case_results_status_check CHECK (status IN ('accepted', 'wrong_answer', 'runtime_error', 'time_limit', 'memory_limit', 'output_limit', 'skipped', 'system_error')),
    CONSTRAINT judge_case_results_time_ms_check CHECK ((time_ms IS NULL) OR (time_ms >= 0)),
    CONSTRAINT judge_case_results_pkey PRIMARY KEY (id)
);

CREATE TABLE judge_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    submission_id bigint,
    stream_id text,
    status text DEFAULT 'pending' NOT NULL,
