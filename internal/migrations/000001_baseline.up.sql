-- Canonical SOJ schema for a fresh PostgreSQL database.
-- Existing deployments must follow docs/schema-cutover.md before upgrading.
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- Tables and constraints

CREATE TABLE artifacts (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    owner_type text NOT NULL,
    owner_id bigint NOT NULL,
    kind text NOT NULL,
    storage_key text NOT NULL,
    checksum_sha256 text NOT NULL,
    size_bytes bigint NOT NULL,
    content_type text NOT NULL,
    created_at timestamptz DEFAULT now() NOT NULL,
    CONSTRAINT artifacts_kind_check CHECK (kind IN ('source', 'stdout', 'stderr', 'compile_output', 'judge_log', 'attachment', 'testcase_archive', 'manifest', 'case_stdout', 'case_stderr', 'output_diff')),
    CONSTRAINT artifacts_owner_type_check CHECK (owner_type IN ('submission', 'run', 'problem', 'testcase', 'judge_attempt', 'judge_case')),
    CONSTRAINT artifacts_size_bytes_check CHECK (size_bytes >= 0),
    CONSTRAINT artifacts_pkey PRIMARY KEY (id)
);

CREATE TABLE audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    actor_user_id bigint,
    action text NOT NULL,
    object_type text NOT NULL,
    object_id bigint,
    reason text DEFAULT '' NOT NULL,
    metadata jsonb DEFAULT '{}'::jsonb NOT NULL,
    created_at timestamptz DEFAULT now() NOT NULL,
    CONSTRAINT audit_events_action_check CHECK (action IN ('user.role.granted', 'user.role.revoked', 'user.disabled', 'user.enabled', 'user.deleted', 'language.enabled', 'language.disabled', 'problem.archived', 'problem.restored', 'contest.archived', 'role.permissions.updated', 'contest.role.granted', 'contest.role.revoked')),
    CONSTRAINT audit_events_object_type_check CHECK (object_type IN ('user', 'language', 'problem', 'contest', 'role')),
    CONSTRAINT audit_events_pkey PRIMARY KEY (id)
);

CREATE TABLE contest_problem_results (
    contest_id bigint NOT NULL,
    user_id bigint NOT NULL,
    problem_id bigint NOT NULL,
    status text DEFAULT 'none' NOT NULL,
    attempts integer DEFAULT 0 NOT NULL,
    accepted_at timestamptz,
    penalty_minutes integer DEFAULT 0 NOT NULL,
    last_submission_id bigint,
    updated_at timestamptz DEFAULT now() NOT NULL,
    CONSTRAINT contest_problem_results_attempts_check CHECK (attempts >= 0),
    CONSTRAINT contest_problem_results_penalty_minutes_check CHECK (penalty_minutes >= 0),
    CONSTRAINT contest_problem_results_status_check CHECK (status IN ('none', 'attempted', 'accepted', 'frozen')),
    CONSTRAINT contest_problem_results_pkey PRIMARY KEY (contest_id, user_id, problem_id)
);

CREATE TABLE contest_problems (
    contest_id bigint NOT NULL,
    problem_id bigint NOT NULL,
    alias text NOT NULL,
    sort_order integer NOT NULL,
    CONSTRAINT contest_problems_sort_order_check CHECK (sort_order > 0),
    CONSTRAINT contest_problems_pkey PRIMARY KEY (contest_id, problem_id)
);

CREATE TABLE contest_registrations (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    contest_id bigint NOT NULL,
    user_id bigint NOT NULL,
    display_name text NOT NULL,
    email text NOT NULL,
    status text DEFAULT 'active' NOT NULL,
    registered_at timestamptz DEFAULT now() NOT NULL,
    accepted_count integer DEFAULT 0 NOT NULL,
    penalty_minutes integer DEFAULT 0 NOT NULL,
    CONSTRAINT contest_registrations_accepted_count_check CHECK (accepted_count >= 0),
    CONSTRAINT contest_registrations_penalty_minutes_check CHECK (penalty_minutes >= 0),
    CONSTRAINT contest_registrations_status_check CHECK (status IN ('active', 'canceled')),
    CONSTRAINT contest_registrations_pkey PRIMARY KEY (id)
);

CREATE TABLE contest_role_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    contest_id bigint NOT NULL,
    user_id bigint NOT NULL,
    role_code text NOT NULL,
    granted_by bigint,
    granted_at timestamptz DEFAULT now() NOT NULL,
    revoked_at timestamptz,
    CONSTRAINT contest_role_assignments_check CHECK ((granted_by IS NULL) OR (granted_by <> user_id)),
    CONSTRAINT contest_role_assignments_role_code_check CHECK (role_code IN ('contest_staff', 'contest_manager', 'contest_judge')),
    CONSTRAINT contest_role_assignments_pkey PRIMARY KEY (id)
);

CREATE TABLE contest_score_snapshot_rows (
    snapshot_id bigint NOT NULL,
    ordinal integer NOT NULL,
    rank integer NOT NULL,
    user_id bigint NOT NULL,
    display_name text NOT NULL,
    accepted_count integer NOT NULL,
    penalty_minutes integer NOT NULL,
    cells jsonb NOT NULL,
    CONSTRAINT contest_score_snapshot_rows_accepted_count_check CHECK (accepted_count >= 0),
    CONSTRAINT contest_score_snapshot_rows_ordinal_check CHECK (ordinal > 0),
    CONSTRAINT contest_score_snapshot_rows_penalty_minutes_check CHECK (penalty_minutes >= 0),
    CONSTRAINT contest_score_snapshot_rows_rank_check CHECK (rank > 0),
    CONSTRAINT contest_score_snapshot_rows_pkey PRIMARY KEY (snapshot_id, ordinal),
    CONSTRAINT contest_score_snapshot_rows_snapshot_id_user_id_key UNIQUE (snapshot_id, user_id)
);

CREATE TABLE contest_score_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    contest_id bigint NOT NULL,
    kind text NOT NULL,
    problems jsonb NOT NULL,
    source_revision bigint DEFAULT 0 NOT NULL,
    generated_at timestamptz DEFAULT now() NOT NULL,
    CONSTRAINT contest_score_snapshots_kind_check CHECK (kind IN ('live', 'frozen', 'final')),
    CONSTRAINT contest_score_snapshots_pkey PRIMARY KEY (id)
);

CREATE TABLE contests (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    owner_user_id bigint NOT NULL,
    title text NOT NULL,
    description text,
    visibility text NOT NULL,
    status text DEFAULT 'draft' NOT NULL,
    start_at timestamptz NOT NULL,
    end_at timestamptz NOT NULL,
    freeze_at timestamptz NOT NULL,
    invite_code_hash text,
    score_revision bigint DEFAULT 0 NOT NULL,
    created_at timestamptz DEFAULT now() NOT NULL,
    updated_at timestamptz DEFAULT now() NOT NULL,
    CONSTRAINT contests_check CHECK (start_at < end_at),
    CONSTRAINT contests_check1 CHECK ((freeze_at >= start_at) AND (freeze_at <= end_at)),
    CONSTRAINT contests_status_check CHECK (status IN ('draft', 'published', 'running', 'ended', 'archived')),
    CONSTRAINT contests_visibility_check CHECK (visibility IN ('public', 'private')),
    CONSTRAINT contests_pkey PRIMARY KEY (id)
);

CREATE TABLE judge_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    submission_id bigint,
    run_id bigint,
    task_id bigint,
    rejudge_batch_id bigint,
    attempt_no integer NOT NULL,
    protocol_version text NOT NULL,
    judge_core_version text NOT NULL,
    judge_engine text NOT NULL,
    judge_agent_id text,
    language_id bigint NOT NULL,
    language_runtime text,
    sandbox_backend text,
    sandbox_profile text,
    testcase_set_id bigint,
    testcase_set_hash text,
    checker_hash text,
    validator_hash text,
    status text NOT NULL,
    time_ms integer,
    memory_kb integer,
    first_failed_case_index integer,
    first_failed_group text,
    compile_output_summary text,
    stderr_summary text,
    checker_message text,
    error_class text,
    error_message text,
    manifest jsonb DEFAULT '{}'::jsonb NOT NULL,
    trace_id text,
    started_at timestamptz,
    finished_at timestamptz,
    created_at timestamptz DEFAULT now() NOT NULL,
    updated_at timestamptz DEFAULT now() NOT NULL,
    CONSTRAINT judge_attempts_attempt_no_check CHECK (attempt_no > 0),
    CONSTRAINT judge_attempts_check CHECK ((((submission_id IS NOT NULL))::integer + ((run_id IS NOT NULL))::integer) = 1),
    CONSTRAINT judge_attempts_memory_kb_check CHECK ((memory_kb IS NULL) OR (memory_kb >= 0)),
    CONSTRAINT judge_attempts_status_check CHECK (status IN ('created', 'compiling', 'running', 'checking', 'accepted', 'wrong_answer', 'compile_error', 'runtime_error', 'time_limit', 'memory_limit', 'output_limit', 'system_error', 'canceled')),
    CONSTRAINT judge_attempts_time_ms_check CHECK ((time_ms IS NULL) OR (time_ms >= 0)),
    CONSTRAINT judge_attempts_pkey PRIMARY KEY (id),
    CONSTRAINT judge_attempts_submission_id_id_key UNIQUE (submission_id, id)
);

CREATE TABLE judge_case_results (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
